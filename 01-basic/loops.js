// 1. for loop

console.log("For Loop:");

for (let i = 1; i <= 5; i++) {
    console.log(i);
}


// 2. while loop

console.log("While Loop:");

let i = 1;

while (i <= 5) {
    console.log(i);
    i++;
}


// 3. do...while loop

console.log("Do While Loop:");

let number = 1;

do {
    console.log(number);
    number++;
} while (number <= 5);


// 4. Print numbers 1 to 10

console.log("Numbers 1 to 10:");

for (let j = 1; j <= 10; j++) {
    console.log(j);
}